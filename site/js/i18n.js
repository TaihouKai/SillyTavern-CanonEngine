const KEY = 'canon-site-lang';
export function detectLang() {
  try { const s = localStorage.getItem(KEY); if (s === 'en' || s === 'zh') return s; } catch { /* storage blocked */ }
  const langs = navigator.languages?.length ? navigator.languages : [navigator.language || 'en'];
  return langs.some((l) => /^zh\b/i.test(l)) ? 'zh' : 'en';
}
export function saveLang(l) { try { localStorage.setItem(KEY, l); } catch { /* storage blocked */ } }

let current = 'en';
export const lang = () => current;
export function t(key, vars = {}) {
  const s = TEXT[current][key] ?? TEXT.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
}
/** Fills every [data-i18n] element (HTML allowed: the texts are ours). */
export function apply(l, vars = {}) {
  current = l;
  document.documentElement.lang = l === 'zh' ? 'zh-CN' : 'en';
  for (const el of document.querySelectorAll('[data-i18n]')) el.innerHTML = t(el.dataset.i18n, vars);
  for (const el of document.querySelectorAll('[data-i18n-ph]')) el.placeholder = t(el.dataset.i18nPh, vars);
  document.dispatchEvent(new CustomEvent('langchange', { detail: l }));
}
