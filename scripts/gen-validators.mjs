// Precompiles every JSON Schema into a standalone ES module so the browser bundle never needs
// runtime code generation (no eval / new Function inside SillyTavern).
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

const schemas = { pack: JSON.parse(readFileSync('schemas/canon-pack.schema.json', 'utf8')) };
for (const f of readdirSync('schemas/runtime')) {
  if (!f.endsWith('.schema.json')) continue;
  const name = f.replace('.schema.json', '').replace(/[^a-zA-Z0-9]/g, '_');
  schemas[name] = JSON.parse(readFileSync(join('schemas/runtime', f), 'utf8'));
}

const ajv = new Ajv2020({ allErrors: true, strict: false, code: { source: true, esm: true } });
const map = {};
for (const [name, schema] of Object.entries(schemas)) {
  const id = schema.$id || `urn:canon-engine:${name}`;
  schema.$id = id;
  ajv.addSchema(schema, id);
  map[name] = id;
}
const code = standaloneCode(ajv, map);
mkdirSync('src/generated', { recursive: true });
writeFileSync('src/generated/validators.js', '// @ts-nocheck\n/* Generated by scripts/gen-validators.mjs. Do not edit. */\n' + code);
writeFileSync(
  'src/generated/validators.d.ts',
  Object.keys(map).map((n) => `export declare const ${n}: { (data: unknown): boolean; errors?: { instancePath: string; message?: string; keyword: string; params: unknown }[] | null };`).join('\n') + '\n',
);
console.log('generated validators:', Object.keys(map).join(', '));
